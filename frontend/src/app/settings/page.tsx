  const [marketStatus, setMarketStatus] = useState<MarketDataStatusResponse | null>(null);
  const [activeConfig, setActiveConfig] = useState<StrategyConfigVersionResponse | null>(null);
  const [actionNotice, setActionNotice] = useState<string | null>(null);
